using Domain.Enums;

namespace Domain.Entities;

/// <summary>Matches the `support_tickets` table.</summary>
public class SupportTicket
{
    public Guid Id { get; set; } = Guid.NewGuid();
    public long UserId { get; set; }
    public SupportTicketType Type { get; set; } = SupportTicketType.General;
    public SupportTicketStatus Status { get; set; } = SupportTicketStatus.Open;
    public DateTime CreatedAt { get; set; } = DateTime.UtcNow;
    public DateTime UpdatedAt { get; set; } = DateTime.UtcNow;

    public bool IsAutoGenerated { get; set; } = false;
    public long? AssignedAgentId { get; set; }
    
    // Links ticket to a rental for disputes
    public Guid? RelatedRentalId { get; set; }

    // Navigation
    public ApplicationUser User { get; set; } = null!;
    public ApplicationUser? AssignedAgent { get; set; }
    public ICollection<SupportMessage> Messages { get; set; } = new List<SupportMessage>();
    public ICollection<SupportTicketEvent> Events { get; set; } = new List<SupportTicketEvent>();

    // Financial Resolution (for dispute tickets)
    public long? FinancialResolutionById { get; set; }
    public DateTimeOffset? FinancialResolutionAt { get; set; }
    public string? FinancialResolutionReason { get; set; }
    public ApplicationUser? FinancialResolutionBy { get; set; }
}

/// <summary>Matches the `support_ticket_events` table for timeline history.</summary>
public class SupportTicketEvent
{
    public Guid Id { get; set; } = Guid.NewGuid();
    public Guid TicketId { get; set; }
    public long? ActorId { get; set; } // Null if system
    public string EventType { get; set; } = string.Empty; // e.g. "Created", "Assigned", "StatusChanged"
    public string Details { get; set; } = string.Empty; // e.g. JSON or text
    public DateTime CreatedAt { get; set; } = DateTime.UtcNow;

    public SupportTicket Ticket { get; set; } = null!;
    public ApplicationUser? Actor { get; set; }
}

/// <summary>Matches the `support_messages` table.</summary>
public class SupportMessage
{
    public Guid Id { get; set; } = Guid.NewGuid();
    public Guid TicketId { get; set; }
    public long SenderId { get; set; }
    public string? Message { get; set; }
    public string? MediaUrl { get; set; }
    public MessageType MessageType { get; set; } = MessageType.Text;
    public DateTime CreatedAt { get; set; } = DateTime.UtcNow;

    // Navigation
    public SupportTicket Ticket { get; set; } = null!;
    public ApplicationUser Sender { get; set; } = null!;
}
