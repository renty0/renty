// ── CREATE TICKET ─────────────────────────────────────────────────────────────

public record CreateTicketCommand(string Type, string Subject, string Message, bool IsAutoGenerated = false) : IRequest<CreateTicketResponse>;
public record CreateTicketResponse(bool Success, string? Error, Guid? TicketId, string Status = "open", SupportMessageDto? AutoReplyMessage = null);

public class CreateTicketCommandValidator : AbstractValidator<CreateTicketCommand>
{
    public CreateTicketCommandValidator()
    {
        RuleFor(x => x.Type).NotEmpty();
        RuleFor(x => x.Subject).NotEmpty().MaximumLength(255);
        RuleFor(x => x.Message).NotEmpty().MaximumLength(2000);
    }
}

public class CreateTicketCommandHandler : IRequestHandler<CreateTicketCommand, CreateTicketResponse>
{
    private readonly IApplicationDbContext _context;
    private readonly IUser _currentUser;
    private readonly INotificationSender _notifier;
    private readonly IRoleService _roleService;

    public CreateTicketCommandHandler(IApplicationDbContext context, IUser currentUser, INotificationSender notifier, IRoleService roleService)
    {
        _context = context;
        _currentUser = currentUser;
        _notifier = notifier;
        _roleService = roleService;
    }

    public async Task<CreateTicketResponse> Handle(CreateTicketCommand request, CancellationToken ct)
    {
        if (_currentUser.Id == null)
            return new CreateTicketResponse(false, "Unauthorized.", null);

        if (!Enum.TryParse<SupportTicketType>(request.Type, true, out var ticketType))
            return new CreateTicketResponse(false, $"Invalid ticket type: {request.Type}", null);

        var ticket = new SupportTicket
        {
            UserId = _currentUser.Id.Value,
            Type = ticketType,
            Status = SupportTicketStatus.Open,
            IsAutoGenerated = request.IsAutoGenerated,
            CreatedAt = DateTime.UtcNow,
            UpdatedAt = DateTime.UtcNow
        };
        _context.SupportTickets.Add(ticket);

        _context.SupportTicketEvents.Add(new SupportTicketEvent
        {
            TicketId = ticket.Id,
            ActorId = _currentUser.Id.Value,
            EventType = "Created",
            Details = request.IsAutoGenerated ? "Ticket auto-generated by system." : "Ticket created by user.",
            CreatedAt = DateTime.UtcNow
        });

        _context.SupportMessages.Add(new SupportMessage
        {
            TicketId = ticket.Id,
            SenderId = _currentUser.Id.Value,
            Message = $"**{request.Subject}**\n\n{request.Message}",
            CreatedAt = DateTime.UtcNow
        });

        // Add auto reply
        var supportUser = await _context.Users.FirstOrDefaultAsync(u => u.Email == "support@renty.com", ct);
        var supportUserId = supportUser?.Id ?? _currentUser.Id.Value;
        
        var autoReplyMsg = new SupportMessage
        {
            TicketId = ticket.Id,
            SenderId = supportUserId,
            Message = "we will contact with u soon",
            CreatedAt = DateTime.UtcNow.AddSeconds(1)
        };
        _context.SupportMessages.Add(autoReplyMsg);

        await _context.SaveChangesAsync(ct);

        var autoReplyDto = new SupportMessageDto(
            autoReplyMsg.Id, 
            autoReplyMsg.SenderId, 
            autoReplyMsg.Message, 
            autoReplyMsg.MediaUrl, 
            autoReplyMsg.MessageType, 
            autoReplyMsg.CreatedAt
        );

        // Notify Support Agents
        var agents = await _roleService.GetUserIdsInRoleAsync(SecurityRoles.Support.ToString());
        var sender = await _context.Users.FirstOrDefaultAsync(u => u.Id == _currentUser.Id.Value, ct);
        var userName = sender?.FirstName ?? "A user";
        
        await _notifier.SendToUsersAsync(
            agents,
            "New Support Ticket",
            $"{userName} opened a new '{ticketType}' ticket.",
            "support",
            $"/support/{ticket.Id}",
            ct,
            titleAr: "تذكرة دعم جديدة",
            messageAr: $"{userName} فتح تذكرة دعم جديدة من نوع '{ticketType}'.");

        return new CreateTicketResponse(true, null, ticket.Id, "open", autoReplyDto);
    }
}

// ── GET TICKETS ───────────────────────────────────────────────────────────────

public record GetTicketsQuery(bool IsSupportAgent = false) : IRequest<GetTicketsResponse>;
public record GetTicketsResponse(List<TicketListDto> Tickets);

public class GetTicketsQueryHandler : IRequestHandler<GetTicketsQuery, GetTicketsResponse>
{
    private readonly IApplicationDbContext _context;
    private readonly IUser _currentUser;

    public GetTicketsQueryHandler(IApplicationDbContext context, IUser currentUser)
    {
        _context = context;
        _currentUser = currentUser;
    }

    public async Task<GetTicketsResponse> Handle(GetTicketsQuery request, CancellationToken ct)
    {
        var query = _context.SupportTickets
            .Include(t => t.User)
            .Include(t => t.AssignedAgent)
            .Include(t => t.Messages)
            .AsQueryable();

        if (!request.IsSupportAgent)
        {
            query = query.Where(t => t.UserId == _currentUser.Id!.Value);
        }

        var tickets = await query
            .OrderByDescending(t => t.UpdatedAt)
            .Select(t => new TicketListDto(
                t.Id, t.Type.ToString(), t.Status.ToString(), t.CreatedAt, t.UpdatedAt,
                t.Messages.OrderByDescending(m => m.CreatedAt).Select(m => m.Message).FirstOrDefault(),
                t.User != null ? t.User.FirstName + " " + t.User.LastName : null,
                t.IsAutoGenerated,
                t.AssignedAgentId,
                t.AssignedAgent != null ? t.AssignedAgent.FirstName + " " + t.AssignedAgent.LastName : null
            ))
            .ToListAsync(ct);

        return new GetTicketsResponse(tickets);
    }
}

// ── GET TICKET DETAILS ────────────────────────────────────────────────────────

public record GetTicketQuery(Guid Id, bool IsSupportAgent = false) : IRequest<GetTicketResponse>;
public record GetTicketResponse(bool Found, string? Error, TicketDetailsDto? Ticket);

public class GetTicketQueryHandler : IRequestHandler<GetTicketQuery, GetTicketResponse>
{
    private readonly IApplicationDbContext _context;
    private readonly IUser _currentUser;

    public GetTicketQueryHandler(IApplicationDbContext context, IUser currentUser)
    {
        _context = context;
        _currentUser = currentUser;
    }

    public async Task<GetTicketResponse> Handle(GetTicketQuery request, CancellationToken ct)
    {
        if (_currentUser.Id == null)
            return new GetTicketResponse(false, "Unauthorized.", null);

        var ticket = await _context.SupportTickets
            .Include(t => t.Messages)
            .Include(t => t.Events).ThenInclude(e => e.Actor)
            .Include(t => t.User)
            .Include(t => t.AssignedAgent)
            .FirstOrDefaultAsync(t => t.Id == request.Id, ct);

        if (ticket == null) return new GetTicketResponse(false, "Ticket not found.", null);

        if (!request.IsSupportAgent && ticket.UserId != _currentUser.Id.Value)
            return new GetTicketResponse(false, "Forbidden.", null);

        var dto = new TicketDetailsDto(
            ticket.Id,
            ticket.Type.ToString(),
            ticket.Status.ToString(),
            ticket.CreatedAt,
            ticket.UpdatedAt,
            ticket.Messages.OrderBy(m => m.CreatedAt).Select(m => new SupportMessageDto(m.Id, m.SenderId, m.Message, m.MediaUrl, m.MessageType, m.CreatedAt)).ToList(),
            ticket.Events.OrderBy(e => e.CreatedAt).Select(e => new SupportTicketEventDto(e.Id, e.EventType, e.Details, e.CreatedAt, e.Actor != null ? e.Actor.FirstName + " " + e.Actor.LastName : "System")).ToList(),
            ticket.User != null ? ticket.User.FirstName + " " + ticket.User.LastName : null,
            ticket.IsAutoGenerated,
            ticket.AssignedAgentId,
            ticket.AssignedAgent != null ? ticket.AssignedAgent.FirstName + " " + ticket.AssignedAgent.LastName : null
        );

        return new GetTicketResponse(true, null, dto);
    }
}

// ── POST MESSAGE ──────────────────────────────────────────────────────────────

public record PostSupportMessageCommand(Guid TicketId, string? Message, string? MediaUrl = null, MessageType MessageType = MessageType.Text, bool IsSupportAgent = false) : IRequest<PostSupportMessageResponse>;
public record PostSupportMessageResponse(bool Success, string? Error, Guid? MessageId, string? Message, string? MediaUrl, MessageType MessageType, DateTime? CreatedAt);

public class PostSupportMessageCommandHandler : IRequestHandler<PostSupportMessageCommand, PostSupportMessageResponse>
{
    private readonly IApplicationDbContext _context;
    private readonly IUser _currentUser;
    private readonly INotificationSender _notifier;
    private readonly IRoleService _roleService;

    public PostSupportMessageCommandHandler(IApplicationDbContext context, IUser currentUser, INotificationSender notifier, IRoleService roleService)
    {
        _context = context;
        _currentUser = currentUser;
        _notifier = notifier;
        _roleService = roleService;
    }

    public async Task<PostSupportMessageResponse> Handle(PostSupportMessageCommand request, CancellationToken ct)
    {
        if (_currentUser.Id == null)
            return new PostSupportMessageResponse(false, "Unauthorized.", null, null, null, MessageType.Text, null);

        var ticket = await _context.SupportTickets.FirstOrDefaultAsync(t => t.Id == request.TicketId, ct);
        if (ticket == null) return new PostSupportMessageResponse(false, "Ticket not found.", null, null, null, MessageType.Text, null);

        // Ticket owner or admin/support can message
        if (!request.IsSupportAgent && ticket.UserId != _currentUser.Id.Value)
            return new PostSupportMessageResponse(false, "Forbidden.", null, null, null, MessageType.Text, null);

        if (ticket.Status == SupportTicketStatus.Resolved || ticket.Status == SupportTicketStatus.Closed)
            return new PostSupportMessageResponse(false, "Ticket is closed or resolved.", null, null, null, MessageType.Text, null);

        var msg = new SupportMessage
        {
            TicketId = request.TicketId,
            SenderId = _currentUser.Id.Value,
            Message = request.Message,
            MediaUrl = request.MediaUrl,
            MessageType = request.MessageType,
            CreatedAt = DateTime.UtcNow
        };
        _context.SupportMessages.Add(msg);

        _context.SupportTicketEvents.Add(new SupportTicketEvent
        {
            TicketId = ticket.Id,
            ActorId = _currentUser.Id.Value,
            EventType = "Message",
            Details = request.IsSupportAgent ? "Support agent replied." : "User replied.",
            CreatedAt = DateTime.UtcNow
        });
        
        // Auto-transition status
        ticket.Status = request.IsSupportAgent 
            ? SupportTicketStatus.AwaitingCustomer 
            : SupportTicketStatus.AwaitingSupport;

        ticket.UpdatedAt = DateTime.UtcNow;
        await _context.SaveChangesAsync(ct);

        if (request.IsSupportAgent)
        {
            await _notifier.SendToUserAsync(
                ticket.UserId,
                "Support Reply",
                "A support agent has replied to your ticket.",
                "support",
                $"/support/{ticket.Id}",
                ct,
                titleAr: "رد الدعم",
                messageAr: "قام وكيل الدعم بالرد على تذكرتك.");
        }
        else
        {
            var agents = await _roleService.GetUserIdsInRoleAsync(SecurityRoles.Support.ToString());
            await _notifier.SendToUsersAsync(
                agents,
                "New Ticket Message",
                $"New message on ticket #{ticket.Id.ToString().Substring(0, 8)}",
                "support",
                $"/support/{ticket.Id}",
                ct,
                titleAr: "رسالة تذكرة جديدة",
                messageAr: $"رسالة جديدة على التذكرة #{ticket.Id.ToString().Substring(0, 8)}");
        }

        return new PostSupportMessageResponse(true, null, msg.Id, msg.Message, msg.MediaUrl, msg.MessageType, msg.CreatedAt);
    }
}

// ── UPDATE TICKET STATUS ──────────────────────────────────────────────────────

public record UpdateTicketStatusCommand(Guid TicketId, string Status) : IRequest<UpdateTicketStatusResponse>;
public record UpdateTicketStatusResponse(bool Success, string? Error, Guid? TicketId, string? Status);

public class UpdateTicketStatusCommandHandler : IRequestHandler<UpdateTicketStatusCommand, UpdateTicketStatusResponse>
{
    private readonly IApplicationDbContext _context;
    private readonly IUser _currentUser;

    public UpdateTicketStatusCommandHandler(IApplicationDbContext context, IUser currentUser)
    {
        _context = context;
        _currentUser = currentUser;
    }

    public async Task<UpdateTicketStatusResponse> Handle(UpdateTicketStatusCommand request, CancellationToken ct)
    {
        if (_currentUser.Id == null) return new UpdateTicketStatusResponse(false, "Unauthorized.", null, null);

        var ticket = await _context.SupportTickets.FirstOrDefaultAsync(t => t.Id == request.TicketId, ct);
        if (ticket == null) return new UpdateTicketStatusResponse(false, "Ticket not found.", null, null);

        if (!Enum.TryParse<SupportTicketStatus>(request.Status, true, out var status))
            return new UpdateTicketStatusResponse(false, $"Invalid status: {request.Status}", null, null);

        if (ticket.Status != status)
        {
            _context.SupportTicketEvents.Add(new SupportTicketEvent
            {
                TicketId = ticket.Id,
                ActorId = _currentUser.Id.Value,
                EventType = "StatusChanged",
                Details = $"Status changed from {ticket.Status} to {status}.",
                CreatedAt = DateTime.UtcNow
            });

            ticket.Status = status;
            ticket.UpdatedAt = DateTime.UtcNow;
            await _context.SaveChangesAsync(ct);
        }

        return new UpdateTicketStatusResponse(true, null, ticket.Id, ticket.Status.ToString());
    }
}

// ── ASSIGN TICKET ─────────────────────────────────────────────────────────────

public record AssignTicketCommand(Guid TicketId) : IRequest<AssignTicketResponse>;
public record AssignTicketResponse(bool Success, string? Error, Guid? TicketId, long? AssignedAgentId);

public class AssignTicketCommandHandler : IRequestHandler<AssignTicketCommand, AssignTicketResponse>
{
    private readonly IApplicationDbContext _context;
    private readonly IUser _currentUser;

    public AssignTicketCommandHandler(IApplicationDbContext context, IUser currentUser)
    {
        _context = context;
        _currentUser = currentUser;
    }

    public async Task<AssignTicketResponse> Handle(AssignTicketCommand request, CancellationToken ct)
    {
        if (_currentUser.Id == null) return new AssignTicketResponse(false, "Unauthorized.", null, null);

        var ticket = await _context.SupportTickets.FirstOrDefaultAsync(t => t.Id == request.TicketId, ct);
        if (ticket == null) return new AssignTicketResponse(false, "Ticket not found.", null, null);

        if (ticket.AssignedAgentId != null)
        {
            if (ticket.AssignedAgentId == _currentUser.Id.Value)
                return new AssignTicketResponse(true, null, ticket.Id, ticket.AssignedAgentId);
            
            return new AssignTicketResponse(false, "Ticket is already assigned to another agent.", null, null);
        }

        ticket.AssignedAgentId = _currentUser.Id.Value;
        ticket.UpdatedAt = DateTime.UtcNow;

        _context.SupportTicketEvents.Add(new SupportTicketEvent
        {
            TicketId = ticket.Id,
            ActorId = _currentUser.Id.Value,
            EventType = "Assigned",
            Details = "Ticket assigned to agent.",
            CreatedAt = DateTime.UtcNow
        });

        await _context.SaveChangesAsync(ct);
        return new AssignTicketResponse(true, null, ticket.Id, ticket.AssignedAgentId);
    }
}

